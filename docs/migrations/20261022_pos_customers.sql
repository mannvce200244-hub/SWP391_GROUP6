BEGIN;

CREATE TABLE IF NOT EXISTS pos_customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150),
    phone VARCHAR(10) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

ALTER TABLE invoices ADD COLUMN IF NOT EXISTS customer_id BIGINT;
ALTER TABLE invoices ADD COLUMN IF NOT EXISTS pos_customer_id BIGINT;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_pos_customer_phone' AND conrelid = 'pos_customers'::regclass) THEN
        ALTER TABLE pos_customers ADD CONSTRAINT ck_pos_customer_phone CHECK (phone ~ '^(03|05|07|08|09)[0-9]{8}$');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_invoice_customer' AND conrelid = 'invoices'::regclass) THEN
        ALTER TABLE invoices ADD CONSTRAINT fk_invoice_customer FOREIGN KEY (customer_id) REFERENCES users(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_invoice_pos_customer' AND conrelid = 'invoices'::regclass) THEN
        ALTER TABLE invoices ADD CONSTRAINT fk_invoice_pos_customer FOREIGN KEY (pos_customer_id) REFERENCES pos_customers(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_invoice_one_customer' AND conrelid = 'invoices'::regclass) THEN
        ALTER TABLE invoices ADD CONSTRAINT ck_invoice_one_customer CHECK (customer_id IS NULL OR pos_customer_id IS NULL);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_invoice_customer ON invoices(customer_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_invoice_pos_customer ON invoices(pos_customer_id, id DESC);

COMMIT;
