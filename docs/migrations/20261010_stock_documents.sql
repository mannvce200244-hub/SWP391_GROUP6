-- Approved stock receipt/issue drafts and quality-controlled confirmation.
-- Preserves existing balances and movement rows. Apply once before deployment.
BEGIN;
CREATE TABLE IF NOT EXISTS stock_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    product_code VARCHAR(50) NOT NULL,
    product_name VARCHAR(200) NOT NULL,
    type VARCHAR(20) NOT NULL CHECK (type IN ('RECEIPT', 'ISSUE')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT', 'CONFIRMED')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    reason VARCHAR(500) NOT NULL,
    created_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_by VARCHAR(255),
    confirmed_at TIMESTAMP WITH TIME ZONE,
    accepted_quantity INTEGER,
    rejected_quantity INTEGER,
    rejection_reason VARCHAR(500),
    quantity_before INTEGER,
    quantity_after INTEGER
);
-- Keep the same invariant when development Hibernate created the table first.
ALTER TABLE stock_documents DROP CONSTRAINT IF EXISTS stock_documents_quantity_check;
ALTER TABLE stock_documents ADD CONSTRAINT stock_documents_quantity_check CHECK (quantity > 0);
ALTER TABLE inventory_movements ADD COLUMN IF NOT EXISTS product_code VARCHAR(50);
ALTER TABLE inventory_movements ADD COLUMN IF NOT EXISTS product_name VARCHAR(200);
ALTER TABLE inventory_movements ADD COLUMN IF NOT EXISTS rejected_quantity INTEGER DEFAULT 0;
ALTER TABLE inventory_movements ADD COLUMN IF NOT EXISTS rejection_reason VARCHAR(500);
ALTER TABLE inventory_movements ADD COLUMN IF NOT EXISTS source_type VARCHAR(20);
ALTER TABLE inventory_movements ADD COLUMN IF NOT EXISTS source_id BIGINT;
UPDATE inventory_movements SET rejected_quantity = 0 WHERE rejected_quantity IS NULL;
CREATE INDEX IF NOT EXISTS idx_stock_documents_product_created ON stock_documents(product_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_inventory_movements_product_created ON inventory_movements(product_id, created_at DESC, id DESC);
COMMIT;
