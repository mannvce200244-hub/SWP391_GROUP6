BEGIN;
CREATE TABLE IF NOT EXISTS saved_delivery_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    customer_name VARCHAR(150) NOT NULL,
    customer_phone VARCHAR(10) NOT NULL,
    customer_email VARCHAR(150) NOT NULL,
    shipping_address VARCHAR(300) NOT NULL,
    notes VARCHAR(500),
    province_id INTEGER,
    ward_id INTEGER,
    street_address VARCHAR(200),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT saved_address_required_text CHECK (
        length(trim(customer_name)) > 0 AND length(trim(shipping_address)) > 0),
    CONSTRAINT saved_address_mobile CHECK (customer_phone ~ '^0[35789][0-9]{8}$'),
    CONSTRAINT saved_address_hierarchy CHECK (
        (province_id IS NULL AND ward_id IS NULL AND street_address IS NULL)
        OR (province_id > 0 AND ward_id > 0 AND length(trim(street_address)) > 0
            AND province_id IS NOT NULL AND ward_id IS NOT NULL AND street_address IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS saved_delivery_addresses_user_id_idx ON saved_delivery_addresses(user_id, id DESC);
-- Development Hibernate update may already have created the table without checks/FK.
ALTER TABLE saved_delivery_addresses ALTER COLUMN version SET DEFAULT 0,
    ALTER COLUMN version SET NOT NULL;
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'saved_delivery_addresses'::regclass
            AND conname = 'saved_delivery_addresses_user_id_fkey') THEN
        ALTER TABLE saved_delivery_addresses ADD CONSTRAINT saved_delivery_addresses_user_id_fkey
            FOREIGN KEY (user_id) REFERENCES users(id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'saved_delivery_addresses'::regclass
            AND conname = 'saved_address_required_text') THEN
        ALTER TABLE saved_delivery_addresses ADD CONSTRAINT saved_address_required_text
            CHECK (length(trim(customer_name)) > 0 AND length(trim(shipping_address)) > 0);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'saved_delivery_addresses'::regclass
            AND conname = 'saved_address_mobile') THEN
        ALTER TABLE saved_delivery_addresses ADD CONSTRAINT saved_address_mobile
            CHECK (customer_phone ~ '^0[35789][0-9]{8}$');
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'saved_delivery_addresses'::regclass
            AND conname = 'saved_address_hierarchy') THEN
        ALTER TABLE saved_delivery_addresses ADD CONSTRAINT saved_address_hierarchy CHECK (
            (province_id IS NULL AND ward_id IS NULL AND street_address IS NULL)
            OR (province_id IS NOT NULL AND ward_id IS NOT NULL AND street_address IS NOT NULL
                AND province_id > 0 AND ward_id > 0 AND length(trim(street_address)) > 0));
    END IF;
END $$;
COMMIT;
