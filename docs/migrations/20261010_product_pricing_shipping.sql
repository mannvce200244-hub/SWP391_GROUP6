-- Apply before deploying product pricing/shipping against the configured PostgreSQL schema.
-- Existing prices/weights are never replaced with invented values.
BEGIN;

ALTER TABLE products ADD COLUMN IF NOT EXISTS billable_weight_kg NUMERIC(10,3);
ALTER TABLE products ADD COLUMN IF NOT EXISTS bulky_surcharge NUMERIC(15,2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS product_promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    name VARCHAR(150) NOT NULL,
    discount_rate NUMERIC(6,4) NOT NULL CHECK (discount_rate >= 0 AND discount_rate <= 1),
    is_active BOOLEAN NOT NULL,
    valid_from TIMESTAMPTZ,
    valid_until TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (valid_from IS NULL OR valid_until IS NULL OR valid_until > valid_from)
);
CREATE INDEX IF NOT EXISTS idx_product_promotion_active ON product_promotions(product_id, is_active);

CREATE TABLE IF NOT EXISTS shipping_settings (
    id BIGINT PRIMARY KEY CHECK (id = 1),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    rate_per_kg NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (rate_per_kg >= 0),
    free_shipping_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    free_shipping_threshold NUMERIC(15,2) CHECK (free_shipping_threshold >= 0 AND free_shipping_threshold = trunc(free_shipping_threshold)),
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (NOT free_shipping_enabled OR free_shipping_threshold IS NOT NULL)
);
INSERT INTO shipping_settings(id, enabled, rate_per_kg, free_shipping_enabled, version, updated_at)
VALUES (1, FALSE, 0, FALSE, 0, CURRENT_TIMESTAMP) ON CONFLICT(id) DO NOTHING;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_product_positive_price' AND conrelid = 'products'::regclass) THEN
        ALTER TABLE products ADD CONSTRAINT ck_product_positive_price CHECK (price > 0) NOT VALID;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_product_shipping_fields' AND conrelid = 'products'::regclass) THEN
        ALTER TABLE products ADD CONSTRAINT ck_product_shipping_fields
            CHECK ((billable_weight_kg IS NULL OR billable_weight_kg > 0) AND bulky_surcharge >= 0 AND bulky_surcharge = trunc(bulky_surcharge)) NOT VALID;
    END IF;
END $$;

COMMIT;

