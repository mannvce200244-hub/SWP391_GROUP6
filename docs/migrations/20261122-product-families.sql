BEGIN;

CREATE TABLE IF NOT EXISTS product_families (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    legacy_key varchar(220) UNIQUE,
    version bigint NOT NULL DEFAULT 0
);
ALTER TABLE products ADD COLUMN IF NOT EXISTS family_id bigint REFERENCES product_families(id);

-- Existing explicit groups define membership; equal product names alone do not.
INSERT INTO product_families (name, legacy_key)
SELECT DISTINCT ON (lower(btrim(variant_group))) name, 'group:' || lower(btrim(variant_group))
FROM products WHERE family_id IS NULL AND variant_group IS NOT NULL AND btrim(variant_group) <> ''
ORDER BY lower(btrim(variant_group)), id
ON CONFLICT (legacy_key) DO NOTHING;

INSERT INTO product_families (name, legacy_key)
SELECT name, 'sku:' || id FROM products
WHERE family_id IS NULL AND (variant_group IS NULL OR btrim(variant_group) = '')
ON CONFLICT (legacy_key) DO NOTHING;

UPDATE products p SET family_id = f.id FROM product_families f
WHERE p.family_id IS NULL AND f.legacy_key = CASE
    WHEN p.variant_group IS NULL OR btrim(p.variant_group) = '' THEN 'sku:' || p.id
    ELSE 'group:' || lower(btrim(p.variant_group)) END;

CREATE INDEX IF NOT EXISTS products_family_idx ON products(family_id, id);
DROP INDEX IF EXISTS products_variant_group_label_uq;
DROP INDEX IF EXISTS products_family_label_uq;
CREATE UNIQUE INDEX products_family_label_uq
    ON products(family_id, lower(btrim(COALESCE(variant_label, '')))) WHERE family_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS products_legacy_variant_label_uq
    ON products(lower(btrim(variant_group)), lower(btrim(variant_label))) WHERE family_id IS NULL AND variant_group IS NOT NULL;

ALTER TABLE products DROP CONSTRAINT IF EXISTS products_variant_pair_check;
ALTER TABLE products ADD CONSTRAINT products_variant_pair_check CHECK (
    (family_id IS NOT NULL AND (variant_group IS NULL OR length(btrim(variant_group)) > 0)
        AND (variant_label IS NULL OR length(btrim(variant_label)) > 0)) OR
    (variant_group IS NULL AND variant_label IS NULL) OR
    (variant_group IS NOT NULL AND variant_label IS NOT NULL
        AND length(btrim(variant_group)) > 0 AND length(btrim(variant_label)) > 0)
);

ALTER TABLE products ALTER COLUMN billable_weight_kg TYPE numeric;

-- Legacy single-SKU programs keep their target until an explicit edit.
ALTER TABLE product_promotions ALTER COLUMN product_id DROP NOT NULL;
CREATE TABLE IF NOT EXISTS product_promotion_targets (
    promotion_id bigint NOT NULL REFERENCES product_promotions(id) ON DELETE CASCADE,
    family_id bigint NOT NULL REFERENCES product_families(id),
    PRIMARY KEY (promotion_id, family_id)
);
CREATE INDEX IF NOT EXISTS product_promotion_targets_family_idx ON product_promotion_targets(family_id, promotion_id);

COMMIT;
