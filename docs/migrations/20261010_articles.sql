-- Apply before deploying cultural articles/guides against the configured PostgreSQL schema.
-- No example content or publication records are inserted.
BEGIN;

CREATE TABLE IF NOT EXISTS articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    summary VARCHAR(500),
    content TEXT NOT NULL,
    type VARCHAR(20) NOT NULL CHECK (type IN ('ARTICLE', 'GUIDE')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED')),
    image_url VARCHAR(500),
    video_url VARCHAR(500),
    product_id BIGINT REFERENCES products(id),
    artisan_id BIGINT REFERENCES artisans(id),
    craft_village_id BIGINT REFERENCES craft_villages(id),
    published_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CHECK (length(btrim(title)) BETWEEN 1 AND 200),
    CHECK (length(btrim(content)) BETWEEN 1 AND 30000),
    CHECK ((status = 'PUBLISHED' AND published_at IS NOT NULL)
        OR (status = 'DRAFT' AND published_at IS NULL))
);

CREATE INDEX IF NOT EXISTS idx_article_publication ON articles(status, published_at);
CREATE INDEX IF NOT EXISTS idx_article_product ON articles(product_id);
CREATE INDEX IF NOT EXISTS idx_article_artisan ON articles(artisan_id);
CREATE INDEX IF NOT EXISTS idx_article_village ON articles(craft_village_id);

COMMIT;
